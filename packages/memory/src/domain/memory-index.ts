/**
 * MEMORY.md builder — the one-screen index of a project's memory.
 *
 * Why: the Director and the owner read the index first and open full records on demand,
 *   so it must stay small enough to read at a glance however long the project lives. It
 *   is generated, never edited. When it would pass the line budget the oldest outcome
 *   pointers are archived (the outcome files stay in git); decisions, rejected approaches
 *   and pending proposals are constraints and are never dropped from it.
 *
 * Exports: buildMemoryIndex(), MEMORY_INDEX_MAX_LINES.
 * Depends on: types/project-memory. Pure, no IO.
 */

import type { IndexEntry, IndexInput } from '#/types/project-memory.types.js';

export const MEMORY_INDEX_MAX_LINES = 200;
const STATEMENT_MAX = 140;

function pointer(entry: IndexEntry): string {
  const flat = entry.statement.replace(/\s+/g, ' ').trim();
  const text =
    flat.length > STATEMENT_MAX ? `${flat.slice(0, STATEMENT_MAX - 1)}…` : flat;

  return `- [${entry.id}](${entry.relPath}): ${text}`;
}

function section(title: string, entries: readonly IndexEntry[]): string[] {
  return entries.length === 0 ? [] : ['', `## ${title}`, ...entries.map(pointer)];
}

/** Renders `MEMORY.md`; ends with a newline; at most `maxLines` lines unless constraints alone exceed it. */
export function buildMemoryIndex(input: IndexInput): string {
  const max = input.maxLines ?? MEMORY_INDEX_MAX_LINES;
  const head = [
    `# Memory of ${input.slug}`,
    '',
    'Generated by Forge on every memory write; do not edit by hand. Open a record for its full text.',
    ...section('Decisions', input.decisions),
    ...section('Rejected approaches', input.rejected),
    ...section('Pending proposals', input.proposed),
  ];

  if (input.superseded > 0) {
    head.push(
      '',
      `${input.superseded} superseded decision(s) are kept in decisions/ and not listed.`,
    );
  }

  // The outcomes heading and the archive note, each after a blank line, need room of their own.
  const room = Math.max(0, max - head.length - 4);
  const newestFirst = [...input.outcomes].reverse();
  const shown = newestFirst.slice(0, room);
  const archived = newestFirst.length - shown.length;
  const lines = [...head];
  if (newestFirst.length > 0 && room > 0) {
    lines.push('', '## Outcomes (newest first)', ...shown.map(pointer));
  }

  if (archived > 0) {
    lines.push(
      '',
      `${archived} older outcome(s) are archived in outcomes/ and not listed.`,
    );
  }

  return `${lines.join('\n')}\n`;
}
